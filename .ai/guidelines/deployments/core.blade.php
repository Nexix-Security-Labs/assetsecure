# Hosting

AssetSecure is self-hosted: it runs on your own servers or on any platform
that can run PHP/Laravel applications (bare metal, VMs, Docker, or a
Laravel-capable cloud host). Prefer configuration through `.env` over code
changes when helping with a specific install, and flag any suggestion that
would make an install diverge from the stock AssetSecure codebase.

